-- Compatibility serialization never exposes extra/internal fields in public_offers.
create function nova_private.legacy_row(kind text,row_data jsonb) returns jsonb
language plpgsql stable set search_path='' as $$
declare result jsonb; k text;
begin
  result := coalesce(row_data->'extra','{}'::jsonb) || (row_data - array['extra','search_document','subscriber_id']);
  foreach k in array array['created_at','updated_at','discovered_at','verified_at','expires_at','last_checked_at','last_sent_at'] loop
    if result->>k is not null then
      result := jsonb_set(result,array[k],to_jsonb(to_char((result->>k)::timestamptz at time zone 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')));
    end if;
  end loop;
  return result;
end;
$$;

create function nova_private.write_row(kind text,input jsonb,expected jsonb default null,operation text default 'upsert')
returns jsonb language plpgsql set search_path='' as $$
declare current_row jsonb; current_legacy jsonb; patch jsonb; extra_data jsonb; columns text; values_sql text;
  assignment text; known text[]; k text; row_id bigint; subscriber bigint; typed_patch jsonb; changed boolean:=false;
begin
  if kind not in ('offers','sources','events','alerts') then raise exception 'Unsupported collection'; end if;
  if jsonb_typeof(input) <> 'object' or not(input ? 'id') then raise exception 'Invalid row'; end if;
  row_id := (input->>'id')::bigint;
  execute format('select to_jsonb(t) from nova_private.%I t where id=$1 for update',kind) into current_row using row_id;
  current_legacy := nova_private.legacy_row(kind,current_row);
  if kind='alerts' and current_row is not null then
    current_legacy := current_legacy || jsonb_build_object('email',(select email from nova_private.subscribers where id=(current_row->>'subscriber_id')::bigint));
  end if;
  if expected is not null then
    if current_row is null then raise exception using errcode='40001',message='Row removed by another writer'; end if;
    for k in select jsonb_object_keys(expected) loop
      if coalesce(current_legacy->k,'null'::jsonb) is distinct from coalesce(expected->k,'null'::jsonb) then
        raise exception using errcode='40001',message='Concurrent row edit';
      end if;
    end loop;
  elsif current_row is not null then
    -- A repeated request may safely repeat the same insertion, never replace a different row.
    if operation <> 'import' then
      for k in select jsonb_object_keys(input) loop
        if current_legacy->k is distinct from input->k then
          raise exception using errcode='40001',message='Concurrent insertion';
        end if;
      end loop;
      return current_legacy;
    end if;
  end if;
  if operation='delete' then
    execute format('delete from nova_private.%I where id=$1',kind) using row_id;
    return null;
  end if;
  patch := input - array['id','updated_at','created_at','search_document','extra'];
  if kind='offers' and input ? 'source_url' and not(input ? 'source_id') then
    patch := patch || jsonb_build_object('source_id',(select id from nova_private.sources where url=input->>'source_url'));
  end if;
  if current_row is null and input ? 'created_at' then patch := patch || jsonb_build_object('created_at',input->'created_at'); end if;
  if kind='alerts' then
    if input ? 'email' then
      insert into nova_private.subscribers(email) values(lower(trim(input->>'email')))
      on conflict(email) do update set email=excluded.email returning id into subscriber;
      patch := (patch - 'email') || jsonb_build_object('subscriber_id',subscriber);
    elsif current_row is null then raise exception 'An alert needs a subscriber'; end if;
  end if;
  select array_agg(attname::text) into known from pg_catalog.pg_attribute
  where attrelid=format('nova_private.%I',kind)::regclass and attnum>0 and not attisdropped and attgenerated='';
  extra_data := coalesce(current_row->'extra','{}'::jsonb) || (patch - known);
  patch := (patch - coalesce((select array_agg(key) from jsonb_object_keys(patch) key where not(key=any(known))),'{}'::text[])) || jsonb_build_object('extra',extra_data);
  execute format('select to_jsonb(jsonb_populate_record(null::nova_private.%I,$1))',kind) into typed_patch using patch;
  for k in select jsonb_object_keys(patch) loop
    if current_row->k is distinct from typed_patch->k then changed:=true; end if;
  end loop;
  -- No unknown JSON keys are ever interpolated into SQL identifiers.
  select string_agg(format('%I',key),','),
    string_agg(format('(jsonb_populate_record(null::nova_private.%I,$1)).%I',kind,key),','),
    string_agg(format('%I=(jsonb_populate_record(null::nova_private.%I,$1)).%I',key,kind,key),',')
  into columns,values_sql,assignment from jsonb_object_keys(patch) key;
  if current_row is null then
    execute format('insert into nova_private.%I(id,%s) select $2,%s returning to_jsonb(%I.*)',kind,columns,values_sql,kind)
    into current_row using patch,row_id;
  elsif changed then
    execute format('update nova_private.%I set %s where id=$2 returning to_jsonb(%I.*)',kind,assignment,kind)
    into current_row using patch,row_id;
  end if;
  if kind='offers' then
    input := nova_private.legacy_row(kind,current_row);
    insert into nova_private.offer_versions(offer_id,content_hash,extraction,approved,evidence)
    values(row_id,md5((input - array['verified_at','updated_at','created_at'])::text),input,
      operation='import' and (coalesce((input->>'official')::boolean,false) or coalesce((input->>'reviewed')::boolean,false)),left(input->>'source_excerpt',500))
    on conflict(offer_id,content_hash) do nothing;
  end if;
  return nova_private.legacy_row(kind,current_row);
end $$;

-- Loads table rows, not nova_state; service_role only. Consumers retain existing IDs/API.
create function public.nova_load_rows() returns jsonb
language sql stable set search_path='' as $$
  select jsonb_build_object(
    'offers',(select coalesce(jsonb_agg(nova_private.legacy_row('offers',to_jsonb(o)) order by id),'[]') from nova_private.offers o),
    'sources',(select coalesce(jsonb_agg(nova_private.legacy_row('sources',to_jsonb(s)) order by id),'[]') from nova_private.sources s),
    'events',(select coalesce(jsonb_agg(nova_private.legacy_row('events',to_jsonb(e)) order by id),'[]') from nova_private.events e),
    'alerts',(select coalesce(jsonb_agg(nova_private.legacy_row('alerts',to_jsonb(a)) || jsonb_build_object('email',s.email) order by a.id),'[]') from nova_private.alerts a join nova_private.subscribers s on s.id=a.subscriber_id),
    'favorites',coalesce((select value from nova_private.app_runtime where key='_legacy_favorites'),'[]'),
    'runtime',coalesce((select jsonb_object_agg(key,value) from nova_private.app_runtime where key not like '\_%'),'{}') ||
      jsonb_build_object('brave',coalesce((select value from nova_private.app_runtime where key='brave'),'{}') ||
        jsonb_build_object('month',to_char(now() at time zone 'UTC','YYYY-MM'),
          'used',coalesce((select used from nova_private.budget_usage where provider='brave' and month=to_char(now() at time zone 'UTC','YYYY-MM')),0),
          'lookupUsed',coalesce((select lookup_used from nova_private.budget_usage where provider='brave' and month=to_char(now() at time zone 'UTC','YYYY-MM')),0)))
  );
$$;

create function public.nova_apply_changes(changes jsonb) returns jsonb
language plpgsql set search_path='' as $$
declare c jsonb; current_value jsonb; k text; has_current boolean;
begin
  if (select mode from nova_private.storage_control where id=1) is distinct from 'normalized' then raise exception 'Normalized storage is not active'; end if;
  if jsonb_typeof(changes)<>'array' or jsonb_array_length(changes)>1000 then raise exception 'Invalid change batch'; end if;
  for c in select value from jsonb_array_elements(changes) loop
    if c->>'collection'='runtime' then
      k := c->'patch'->>'key';
      if k is null or k like '\_%' then raise exception 'Reserved runtime key'; end if;
      select value into current_value from nova_private.app_runtime where key=k for update;
      has_current := found;
      if coalesce(current_value,'null'::jsonb) is distinct from coalesce(c->'expected'->'value','null'::jsonb) then raise exception using errcode='40001',message='Concurrent runtime edit'; end if;
      if has_current then
        update nova_private.app_runtime set value=c->'patch'->'value' where key=k;
      else
        insert into nova_private.app_runtime(key,value) values(k,c->'patch'->'value') on conflict do nothing;
        if not found then raise exception using errcode='40001',message='Concurrent runtime insertion'; end if;
      end if;
    else
      perform nova_private.write_row(c->>'collection',c->'patch',nullif(c->'expected','null'::jsonb),coalesce(c->>'operation','upsert'));
    end if;
  end loop;
  return jsonb_build_object('applied',jsonb_array_length(changes));
end $$;

-- Atomic ID blocks preserve numeric IDs used by the web and extension.
create function public.nova_reserve_ids(amount integer default 1000) returns jsonb
language plpgsql set search_path='' as $$
declare kind text; seq_name text; first_id bigint; last_id bigint; result jsonb := '{}';
begin
  if amount not between 1 and 10000 then raise exception 'Invalid ID block'; end if;
  perform pg_advisory_xact_lock(71001);
  foreach kind in array array['offers','sources','events','alerts'] loop
    seq_name := pg_get_serial_sequence(format('nova_private.%I',kind),'id');
    first_id := nextval(seq_name::regclass);
    last_id := first_id + amount - 1;
    perform setval(seq_name::regclass,last_id,true);
    result := result || jsonb_build_object(kind,jsonb_build_object('next',first_id,'last',last_id));
  end loop;
  return result;
end $$;

create function public.nova_reserve_brave(month_key text,purpose text,total_limit integer) returns jsonb
language plpgsql set search_path='' as $$
declare usage nova_private.budget_usage; cap integer := least(greatest(total_limit,0),600);
begin
  if month_key <> to_char(now() at time zone 'UTC','YYYY-MM') or purpose not in ('discovery','lookup') then raise exception 'Invalid budget request'; end if;
  insert into nova_private.budget_usage(provider,month) values('brave',month_key) on conflict do nothing;
  select * into usage from nova_private.budget_usage where provider='brave' and month=month_key for update;
  if usage.used >= cap then return jsonb_build_object('skipped','monthly_limit','used',usage.used,'lookupUsed',usage.lookup_used); end if;
  if purpose='lookup' and usage.lookup_used >=100 then return jsonb_build_object('skipped','lookup_limit','used',usage.used,'lookupUsed',usage.lookup_used); end if;
  update nova_private.budget_usage set used=used+1,lookup_used=lookup_used+case when purpose='lookup' then 1 else 0 end
  where provider='brave' and month=month_key returning * into usage;
  return jsonb_build_object('used',usage.used,'lookupUsed',usage.lookup_used);
end $$;

create function public.nova_create_alert(input jsonb) returns jsonb
language plpgsql set search_path='' as $$
declare subscriber bigint; result nova_private.alerts;
begin
  if (select mode from nova_private.storage_control where id=1) is distinct from 'normalized' then raise exception 'Normalized storage is not active'; end if;
  insert into nova_private.subscribers(email) values(lower(trim(input->>'email')))
  on conflict(email) do update set email=excluded.email returning id into subscriber;
  insert into nova_private.alerts(id,subscriber_id,query,country,category,verification,frequency,timezone)
  values((input->>'id')::bigint,subscriber,coalesce(input->>'query',''),coalesce(input->>'country','ALL'),
    coalesce(input->>'category','ALL'),coalesce(input->>'verification','ALL'),coalesce(input->>'frequency','daily'),coalesce(input->>'timezone','America/Bogota'))
  on conflict(subscriber_id,query,country,category,verification,frequency) where enabled
  do update set enabled=true returning * into result;
  return nova_private.legacy_row('alerts',to_jsonb(result)) || jsonb_build_object('email',lower(trim(input->>'email')));
end $$;

