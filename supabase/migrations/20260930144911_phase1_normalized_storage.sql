-- Idempotent backfill. Existing IDs are imported, never invented or published anew.
create function nova_private.import_state(payload jsonb) returns void
language plpgsql set search_path='' as $$
declare r jsonb; k text; v jsonb; seq_name text; maximum bigint; seq_value bigint;
begin
  if jsonb_typeof(payload)<>'object' then raise exception 'Invalid legacy snapshot'; end if;
  perform pg_advisory_xact_lock(71001);
  for r in select value from jsonb_array_elements(coalesce(payload->'sources','[]')) loop
    perform nova_private.write_row('sources',r,null,'import');
  end loop;
  for r in select value from jsonb_array_elements(coalesce(payload->'offers','[]')) loop
    if not(r ? 'source_id') then
      r := r || jsonb_build_object('source_id',(select id from nova_private.sources where url=r->>'source_url'));
    end if;
    perform nova_private.write_row('offers',r,null,'import');
  end loop;
  for r in select value from jsonb_array_elements(coalesce(payload->'events','[]')) loop
    if r ? 'source_id' and not exists(select 1 from nova_private.sources where id=(r->>'source_id')::bigint) then
      r := (r-'source_id') || jsonb_build_object('legacy_source_id',r->'source_id');
    end if;
    if r ? 'offer_id' and not exists(select 1 from nova_private.offers where id=(r->>'offer_id')::bigint) then
      r := (r-'offer_id') || jsonb_build_object('legacy_offer_id',r->'offer_id');
    end if;
    perform nova_private.write_row('events',r,null,'import');
  end loop;
  for r in select value from jsonb_array_elements(coalesce(payload->'alerts','[]')) loop
    perform nova_private.write_row('alerts',r,null,'import');
  end loop;
  -- Match deletions performed by the legacy owner before cutover; never run in normalized mode.
  delete from nova_private.alerts where id not in (select (value->>'id')::bigint from jsonb_array_elements(coalesce(payload->'alerts','[]')));
  for k,v in select key,value from jsonb_each(coalesce(payload->'runtime','{}')) loop
    if k='brave' then
      if v ? 'month' then
        insert into nova_private.budget_usage(provider,month,used,lookup_used)
        values('brave',v->>'month',greatest(coalesce((v->>'used')::integer,0),0),greatest(coalesce((v->>'lookupUsed')::integer,0),0))
        on conflict(provider,month) do update set used=greatest(budget_usage.used,excluded.used),lookup_used=greatest(budget_usage.lookup_used,excluded.lookup_used);
      end if;
      v := v - array['month','used','lookupUsed'];
    end if;
    insert into nova_private.app_runtime(key,value) values(k,v) on conflict(key) do update set value=excluded.value where app_runtime.value is distinct from excluded.value;
  end loop;
  insert into nova_private.app_runtime(key,value) values('_legacy_favorites',coalesce(payload->'favorites','[]'))
  on conflict(key) do update set value=excluded.value where app_runtime.value is distinct from excluded.value;
  v := payload->'runtime'->'worker';
  if v ? 'lastWindow' then
    insert into nova_private.worker_runs(job_key,window_id,status,started_at,finished_at,summary)
    values('legacy:' || (v->>'lastWindow'),(v->>'lastWindow')::bigint,
      case when v->>'lastError' is not null then 'failed' when v->>'lastCompletedAt' is not null then 'completed' else 'started' end,
      (v->>'lastStartedAt')::timestamptz,(v->>'lastCompletedAt')::timestamptz,coalesce(v->'lastScanResult','{}'))
    on conflict(job_key) do update set status=excluded.status,finished_at=excluded.finished_at,summary=excluded.summary;
  end if;
  foreach k in array array['offers','sources','events','alerts'] loop
    seq_name := pg_get_serial_sequence(format('nova_private.%I',k),'id');
    execute format('select coalesce(max(id),0) from nova_private.%I',k) into maximum;
    execute format('select last_value from %s',seq_name) into seq_value;
    perform setval(seq_name::regclass,greatest(maximum,seq_value,1),true);
  end loop;
end $$;

create function public.nova_import_snapshot() returns jsonb
language plpgsql set search_path='' as $$
declare payload jsonb;
begin
  perform pg_advisory_xact_lock(71000);
  if (select mode from nova_private.storage_control where id=1) is distinct from 'legacy' then raise exception 'Import is disabled after cutover'; end if;
  select state into payload from public.nova_state where id=1;
  if payload is not null then perform nova_private.import_state(payload); end if;
  return jsonb_build_object('offers',(select count(*) from nova_private.offers),'sources',(select count(*) from nova_private.sources),
    'alerts',(select count(*) from nova_private.alerts),'events',(select count(*) from nova_private.events));
end $$;

create function nova_private.sync_legacy_snapshot() returns trigger
language plpgsql set search_path='' as $$
begin
  perform pg_advisory_xact_lock(71000);
  if (select mode from nova_private.storage_control where id=1)='normalized' then
    raise exception 'Legacy snapshot writes disabled; deploy normalized code or use documented rollback';
  end if;
  perform nova_private.import_state(new.state);
  return new;
end $$;
create trigger sync_normalized_rows after insert or update on public.nova_state
for each row execute function nova_private.sync_legacy_snapshot();

create function public.nova_activate_rows() returns jsonb
language plpgsql set search_path='' as $$
begin
  -- Lock order matches an old snapshot writer: nova_state first, then advisory lock.
  perform 1 from public.nova_state where id=1 for update;
  perform pg_advisory_xact_lock(71000);
  if (select mode from nova_private.storage_control where id=1)='legacy' then
    perform public.nova_import_snapshot();
    update nova_private.storage_control set mode='normalized' where id=1;
  end if;
  return public.nova_load_rows();
end $$;

-- Native counters remain authoritative when a different process reserved an attempt.
create function public.nova_export_rollback() returns jsonb
language plpgsql set search_path='' as $$
declare state jsonb; seq jsonb:='{}'; k text; n bigint;
begin
  state := public.nova_load_rows();
  foreach k in array array['offers','sources','events','alerts'] loop
    execute format('select coalesce(max(id),0) from nova_private.%I',k) into n;
    seq := seq || jsonb_build_object(k,n);
  end loop;
  return state || jsonb_build_object('seq',seq || jsonb_build_object('favorites',0));
end $$;

revoke all on all functions in schema nova_private from public,anon,authenticated;
grant execute on all functions in schema nova_private to service_role;
revoke all on function public.nova_import_snapshot(),public.nova_activate_rows(),public.nova_export_rollback() from public,anon,authenticated;
grant execute on function public.nova_import_snapshot(),public.nova_activate_rows(),public.nova_export_rollback() to service_role;
-- Preserve an existing empty/bootstrap table and all of its private contents.
select public.nova_import_snapshot();
notify pgrst, 'reload schema';
commit;
